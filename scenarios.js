// Короткий текст повідомлення (для прев'ю і пульта).
export function msgPreview(m) {
  if (!m) return "";
  if (m.type === "voice") return `🎤 Голосове ${m.dur}: «${m.transcript}»`;
  if (m.type === "sticker") return `Стікер ${m.t}`;
  if (m.type === "burst") return m.t.join(" · ");
  return m.t;
}

